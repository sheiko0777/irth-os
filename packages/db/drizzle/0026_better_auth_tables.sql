-- Better Auth's own tables.
--
-- The app shipped with a Better Auth client and a verifySession() that fetched
-- /api/auth/get-session, but no server instance, no route handler, and no
-- tables. Every auth call 404'd, so login could never succeed.
--
-- Table and column names come from `@better-auth/cli generate`, not by hand:
-- the adapter matches them exactly, and a near-miss fails at runtime rather
-- than at build time.
--
-- The organization plugin is deliberately not enabled, so no `organization` or
-- `member` table is created here. Tenancy stays with `organizations` and
-- `org_members`, which every query in the app already scopes by.

