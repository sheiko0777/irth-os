export const createDb = (url: string) => {
  const client = postgres(url, { prepare: false });
  return drizzle(client, { schema });
};

export type DbInstance = ReturnType<typeof createDb>;

let cachedDb: DbInstance | undefined;

function resolveDefaultDb(): DbInstance {
  if (!cachedDb) {
    const url = process.env.DATABASE_URL;
    if (!url) {
      throw new Error('DATABASE_URL is not set');
    }
    cachedDb = createDb(url);
  }
  return cachedDb;
}

/**
 * Convenience default connection for consumers that don't need a specific
 * URL (most of the admin app, the outbox worker). Built lazily on first
 * property access rather than at module-evaluation time: both this package
 * and the Next.js admin app can run on Cloudflare's edge runtimes, where env
 * vars/secrets are only guaranteed wired up once a request is in flight —
 * an eager `createDb(process.env.DATABASE_URL!)` here would run the moment
 * anything imports `@irth/db`, before that's guaranteed true, and throw for
 * every consumer instead of just the one that needed the DB. Callers that
 * already have a request-scoped URL should call `createDb(url)` directly.
 */
export const db: DbInstance = new Proxy({} as DbInstance, {
  get(_target, prop) {
    const real = resolveDefaultDb();
    const value = Reflect.get(real, prop, real);
    return typeof value === 'function' ? value.bind(real) : value;
  },
});

// Accepts the plain db or a transaction handle — both expose the same
// insert() shape, and passing tx keeps the audit row in the transaction.
type AuditWriter = Pick<DbInstance, 'insert'>;

export async function withAudit<T extends { id?: string }>(
    dbInstance: AuditWriter,
    operation: () => Promise<T>,
    auditData: { orgId: string, userId: string | null, action: string, tableName: string, changes: Record<string, unknown> }
) {
    const result = await operation();
    const recordId = result?.id || 'unknown_id';
    await dbInstance.insert(auditLog).values({ ...auditData, recordId });
    return result;
}